export async function executediagnosticsApproveVendor(c: Context) {

    try {
      const body = await c.req.json();
      const vendorId = body.vendorId || body.id;

      if (!vendorId) {
        return c.json({ error: 'Vendor ID required' }, 400);
      }

      // Update vendor status to approved
      const updateResult = await diagnostics_approve_vendorRepo.dbDiagnosticsApproveVendor0(vendorId)

      if (updateResult.rows.length === 0) {
        return c.json({ error: 'Vendor not found' }, 404);
      }

      return c.json({
        success: true,
        message: 'Vendor approved successfully',
        vendor: updateResult.rows[0]
      });
    } catch (error: any) {
      console.error('[Diagnostics] Error approving vendor:', error);
      return c.json({ error: error.message }, 500);
    }
}
