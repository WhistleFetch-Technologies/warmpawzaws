#!/usr/bin/env node
/**
 * Write temporary env vars for local smoke against dev RDS (Secrets Manager only — no RDS queries).
 * Usage:
 *   node scripts/prepare-smoke-env.js > scripts/.env.smoke.generated
 *   npx dotenv -e scripts/.env.smoke.generated -e .env.local -- npx serverless offline --config serverless.local.yml
 */
const { SecretsManagerClient, GetSecretValueCommand } = require('@aws-sdk/client-secrets-manager');

const REGION = process.env.AWS_REGION || 'ap-south-1';
const SECRET_ARN =
  process.env.DB_SECRET_ARN ||
  'arn:aws:secretsmanager:ap-south-1:057442119249:secret:warmpawz-dev-rds-master-20260106164510791100000002-WqZcjI';
const DB_HOST =
  process.env.DB_HOST || 'warmpawz-dev-cluster.cluster-cpgs0s0iyq8o.ap-south-1.rds.amazonaws.com';

async function main() {
  const sm = new SecretsManagerClient({ region: REGION });
  const sec = await sm.send(new GetSecretValueCommand({ SecretId: SECRET_ARN }));
  const creds = JSON.parse(sec.SecretString);
  const user = creds.username || creds.user;
  const password = creds.password;
  const lines = [
    '# Generated by prepare-smoke-env.js — dev RDS for local serverless smoke only',
    `DB_HOST=${DB_HOST}`,
    'DB_PORT=5432',
    'DB_NAME=warmpawz',
    `DB_USER=${user}`,
    `DB_PASSWORD=${password}`,
    'DB_SSL=true',
    'UAT_MODE=true',
  ];
  process.stdout.write(lines.join('\n') + '\n');
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
